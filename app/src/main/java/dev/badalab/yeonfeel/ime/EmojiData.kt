    /** 부분 일치 검색. 한글 초성만 입력하면 키워드의 초성과도 맞춘다. */
    fun search(text: String): List<String> {
        val query = text.trim()
        if (query.isEmpty()) return emptyList()
        val choseongQuery = query.all { it in CHOSEONG }
        val result = LinkedHashSet<String>()
        keywords.forEach { (words, emojis) ->
            val hit = if (choseongQuery) {
                choseongOf(words).contains(query)
            } else {
                words.contains(query, ignoreCase = true)
            }
            if (hit) result.addAll(emojis.split(" "))
        }
        return result.toList()
    }

    private const val CHOSEONG = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"

    private fun choseongOf(text: String): String = buildString {
        text.forEach { ch ->
            if (ch in '가'..'힣') append(CHOSEONG[(ch - '가') / 588]) else append(ch)
        }
    }

    private var cached: List<Category>? = null

    fun categories(): List<Category> {
        cached?.let { return it }
        val paint = Paint()
        val filtered = rawCategories.map { category ->
            if (category.wide) {
                category
            } else {
                category.copy(emojis = category.emojis.filter { paint.hasGlyph(it) })
            }
        }.filter { it.emojis.isNotEmpty() }
        cached = filtered
        return filtered
    }

